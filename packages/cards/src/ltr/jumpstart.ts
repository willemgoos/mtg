function randomRareSlot(color: 'W' | 'U' | 'B' | 'R' | 'G'): Pick<Packet, 'slots'> {
  const built = LTR_RANDOM_RARES[color].filter((n) => n in LORD_OF_THE_RINGS_BEHAVIORS);
  return built.length ? { slots: [built.map((card) => ({ card, weight: 1 }))] } : {};
}

